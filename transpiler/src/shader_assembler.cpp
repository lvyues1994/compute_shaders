#include "shader_assembler.hpp"

#include <vector>

namespace tc::transpiler {

namespace {

enum class Dialect : std::uint8_t {
    Desktop,
    Es,
    Vulkan,
};

char const *accessQualifier(tc::Access const access) {
    switch (access) {
    case tc::Access::ReadOnly:
        return "readonly ";
    case tc::Access::WriteOnly:
        return "writeonly ";
    case tc::Access::ReadWrite:
        return "";
    }
    return "";
}

std::string imageType(ImageModel const &image) {
    auto const prefix = image.format.encoding != tc::Encoding::Integer ? "" : image.format.isSigned ? "i" : "u";
    return std::string{prefix} + "image" + (image.dim == tc::Dim::D3 ? "3D" : "2D");
}

bool isR32(tc::ImageFormat const &format) {
    return format.channelCount == 1 and format.bitsPerChannel == 32;
}

// OpenGL ES requires images to be readonly or writeonly, except r32 formats.
tc::Access imageAccess(ImageModel const &image) {
    auto const access = accessOf(image.usage);
    if (not image.usage.read and not image.usage.written) {
        return tc::Access::ReadOnly;
    }
    return access;
}

std::string esUnavailableReason(KernelModel const &kernel, GlslBody const &body) {
    if (body.usesDouble) {
        return "the kernel uses double precision, which OpenGL ES lacks";
    }
    for (auto const &image : kernel.images) {
        if (not tc::isPortableStorageFormat(image.format)) {
            return "image '" + image.name + "' uses format " + tc::glslFormatQualifier(image.format)
                 + ", which OpenGL ES 3.1 cannot use for storage images";
        }
        if (imageAccess(image) == tc::Access::ReadWrite and not isR32(image.format)) {
            return "image '" + image.name + "' is read and written; OpenGL ES allows that only for r32 formats";
        }
    }
    return {};
}

std::string assemble(KernelModel const &kernel, GlslBody const &body, std::string const &sourceName,
                     Dialect const dialect) {
    auto text = std::string{};
    switch (dialect) {
    case Dialect::Desktop:
        text += "#version 430\n";
        break;
    case Dialect::Es:
        text += "#version 310 es\nprecision highp float;\nprecision highp int;\n";
        break;
    case Dialect::Vulkan:
        text += "#version 450\n";
        break;
    }
    text += "// Generated by tc-transpile from " + sourceName + ". Do not edit.\n\n";
    text += "layout(local_size_x = " + std::to_string(kernel.localSize[0])
          + ", local_size_y = " + std::to_string(kernel.localSize[1])
          + ", local_size_z = " + std::to_string(kernel.localSize[2]) + ") in;\n\n";

    for (auto const &definition : body.structs) {
        text += definition + "\n\n";
    }
    for (std::size_t i = 0; i < kernel.buffers.size(); ++i) {
        auto const &buffer = kernel.buffers[i];
        text += "layout(std430, binding = " + std::to_string(buffer.binding) + ") "
              + accessQualifier(accessOf(buffer.usage)) + "buffer _" + buffer.name + "Layout {\n    "
              + body.bufferTypes[i] + " " + buffer.name + "[];\n};\n";
    }
    for (auto const &image : kernel.images) {
        auto const precision = dialect == Dialect::Es ? "highp " : "";
        text += "layout(binding = " + std::to_string(image.binding) + ", " + tc::glslFormatQualifier(image.format)
              + ") " + accessQualifier(imageAccess(image)) + "uniform " + precision + imageType(image) + " "
              + image.name + ";\n";
    }
    if (dialect == Dialect::Vulkan) {
        if (not kernel.uniforms.empty()) {
            text += "layout(push_constant) uniform TcPushConstants {\n";
            for (std::size_t i = 0; i < kernel.uniforms.size(); ++i) {
                auto const &uniform = kernel.uniforms[i];
                text += "    layout(offset = " + std::to_string(uniform.pushConstantOffset) + ") "
                      + body.uniformTypes[i] + " " + uniform.name + ";\n";
            }
            text += "};\n";
        }
    } else {
        for (std::size_t i = 0; i < kernel.uniforms.size(); ++i) {
            auto const &uniform = kernel.uniforms[i];
            text += "layout(location = " + std::to_string(uniform.location) + ") uniform " + body.uniformTypes[i] + " "
                  + uniform.name + ";\n";
        }
    }
    text += "\n";
    for (auto const &constant : body.constants) {
        text += constant + "\n";
    }
    if (not body.constants.empty()) {
        text += "\n";
    }
    for (auto const &prototype : body.prototypes) {
        text += prototype + "\n";
    }
    if (not body.prototypes.empty()) {
        text += "\n";
    }
    for (auto const &function : body.functions) {
        text += function + "\n\n";
    }
    return text;
}

} // namespace

ShaderVariants assembleShaders(KernelModel const &kernel, GlslBody const &body, std::string const &sourceName) {
    auto variants = ShaderVariants{};
    variants.desktop = assemble(kernel, body, sourceName, Dialect::Desktop);
    variants.vulkan = assemble(kernel, body, sourceName, Dialect::Vulkan);
    variants.esUnavailableReason = esUnavailableReason(kernel, body);
    if (variants.esUnavailableReason.empty()) {
        variants.es = assemble(kernel, body, sourceName, Dialect::Es);
    }
    return variants;
}

} // namespace tc::transpiler
