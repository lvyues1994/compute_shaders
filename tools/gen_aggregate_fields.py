#!/usr/bin/env python3
"""Generate tc/include/tc/detail/aggregate_fields.hpp.

C++17 has no reflection. The packed table layout still needs the fields of
a plain aggregate struct in declaration order; a structured binding with
exactly as many names as the struct has fields provides them. One overload
per field count is emitted here.
"""

import pathlib

MAX_FIELDS = 32
HEADER = pathlib.Path(__file__).resolve().parent.parent / "tc/include/tc/detail/aggregate_fields.hpp"


def overload(n: int) -> str:
    names = ", ".join(f"f{i}" for i in range(n))
    return (
        "template <class T>\n"
        f"auto tieFields(T &value, FieldCountTag<{n}>) noexcept {{\n"
        f"    auto &[{names}] = value;\n"
        f"    return std::tie({names});\n"
        "}\n"
    )


def main() -> None:
    parts = [
        "// Generated by tools/gen_aggregate_fields.py. Do not edit.\n"
        "#pragma once\n\n"
        "#include <cstddef>\n"
        "#include <tuple>\n\n"
        "namespace tc::detail {\n\n"
        f"inline constexpr std::size_t kMaxAggregateFields = {MAX_FIELDS};\n\n"
        "template <std::size_t N>\n"
        "struct FieldCountTag {};\n\n"
        "// References to the N fields of an aggregate, in declaration order.\n"
    ]
    parts += [overload(n) for n in range(1, MAX_FIELDS + 1)]
    parts.append("\n} // namespace tc::detail\n")
    HEADER.write_text("\n".join(parts))


if __name__ == "__main__":
    main()
