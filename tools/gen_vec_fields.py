#!/usr/bin/env python3
"""Generate tc/include/tc/detail/vec_fields.hpp.

C++17 has no string-literal template parameters, so GLSL swizzles such as
`v.xy` are spelled `v.xy()` and every combination is emitted here as a
read-only member function of the matching VecFields<T, N> specialisation.
"""

import itertools
import pathlib

LETTERS = "xyzw"
HEADER = pathlib.Path(__file__).resolve().parent.parent / "tc/include/tc/detail/vec_fields.hpp"


def component_body(n: int) -> str:
    names = LETTERS[:n]
    expr = names[-1]
    for i in reversed(range(n - 1)):
        expr = f"i == {i} ? {names[i]} : {expr}"
    return expr


def specialisation(n: int) -> str:
    names = LETTERS[:n]
    align = "2" if n == 2 else "4"
    lines = [
        "template <class T>",
        f"struct alignas({align} * sizeof(T)) VecFields<T, {n}> {{",
    ]
    lines += [f"    T {c}{{}};" for c in names]
    lines += [
        "",
        f"    constexpr T &component(int const i) noexcept {{ return {component_body(n)}; }}",
        f"    constexpr T const &component(int const i) const noexcept {{ return {component_body(n)}; }}",
        "",
    ]
    for length in range(2, 5):
        for combo in itertools.product(names, repeat=length):
            name = "".join(combo)
            args = ", ".join(combo)
            lines.append(
                f"    constexpr vec<T, {length}> {name}() const noexcept {{ return vec<T, {length}>{{{args}}}; }}"
            )
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    parts = [
        "// Generated by tools/gen_vec_fields.py. Do not edit by hand.",
        "#pragma once",
        "",
        "namespace tc {",
        "",
        "template <class T, int N>",
        "struct vec;",
        "",
        "namespace detail {",
        "",
        "template <class T, int N>",
        "struct VecFields;",
        "",
    ]
    for n in (2, 3, 4):
        parts.append(specialisation(n))
        parts.append("")
    parts += ["} // namespace detail", "", "} // namespace tc", ""]
    HEADER.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text("\n".join(parts))


if __name__ == "__main__":
    main()
